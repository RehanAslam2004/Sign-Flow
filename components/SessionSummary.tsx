'use client';

import React, { useState } from 'react';
import { CheckCircle2, Clock, Sparkles, Copy, Check, Download, RotateCcw } from 'lucide-react';

export interface SessionSummaryProps {
  durationSeconds: number;
  confirmedSigns: string[];
  startTime?: number | null;
  endTime?: number | null;
  onStartNewSession: () => void;
}

export function formatDuration(totalSeconds: number): string {
  const safeSeconds = Math.max(0, Math.floor(totalSeconds));
  const mins = Math.floor(safeSeconds / 60);
  const secs = safeSeconds % 60;
  return `${mins.toString().padStart(2, '0')}:${secs.toString().padStart(2, '0')}`;
}

export default function SessionSummary({
  durationSeconds,
  confirmedSigns,
  startTime,
  endTime,
  onStartNewSession,
}: SessionSummaryProps) {
  const [copied, setCopied] = useState(false);

  const formattedDuration = formatDuration(durationSeconds);
  const totalSignsCount = confirmedSigns.length;
  const transcriptText = confirmedSigns.join(' • ');

  const handleCopy = async () => {
    if (!transcriptText) return;
    try {
      await navigator.clipboard.writeText(transcriptText);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (err) {
      console.warn('Failed to copy transcript to clipboard', err);
    }
  };

  const handleDownload = () => {
    const lines = [
      '==========================================',
      'SignFlow — Communication Session Summary',
      '==========================================',
      `Date: ${new Date(endTime || Date.now()).toLocaleString()}`,
      `Duration: ${formattedDuration}`,
      `Total Confirmed Signs: ${totalSignsCount}`,
      '',
      '--- Your Session Transcript ---',
      transcriptText || 'No signs confirmed during this session.',
      '',
      'Generated by SignFlow (Build With AI: Basics)',
      '==========================================',
    ];
    const blob = new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `signflow-session-${Date.now()}.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="max-w-xl mx-auto w-full px-4 py-8 sm:py-12 animate-fadeIn">
      <div className="bg-white rounded-3xl border border-slate-200/90 shadow-sm p-6 sm:p-8 flex flex-col gap-6">
        {/* Header */}
        <div className="flex items-start gap-3.5">
          <div className="w-10 h-10 rounded-2xl bg-teal-50 border border-teal-200 flex items-center justify-center shrink-0 text-[#068D9D]">
            <CheckCircle2 className="w-6 h-6" aria-hidden="true" />
          </div>
          <div>
            <h1 className="text-xl sm:text-2xl font-extrabold text-slate-900 tracking-tight">
              Session completed
            </h1>
            <p className="text-xs sm:text-sm text-slate-500 mt-0.5">
              Your communication session has ended. Here's your summary.
            </p>
          </div>
        </div>

        {/* Metric Badges */}
        <div className="grid grid-cols-2 gap-3 sm:gap-4">
          <div className="bg-slate-50/80 rounded-2xl border border-slate-200/70 p-4 flex flex-col gap-1">
            <div className="flex items-center gap-1.5 text-slate-500 text-xs font-medium">
              <Clock className="w-3.5 h-3.5 text-slate-400" aria-hidden="true" />
              <span>Session duration</span>
            </div>
            <span className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight font-mono">
              {formattedDuration}
            </span>
          </div>

          <div className="bg-slate-50/80 rounded-2xl border border-slate-200/70 p-4 flex flex-col gap-1">
            <div className="flex items-center gap-1.5 text-slate-500 text-xs font-medium">
              <Sparkles className="w-3.5 h-3.5 text-slate-400" aria-hidden="true" />
              <span>Confirmed signs</span>
            </div>
            <span className="text-2xl sm:text-3xl font-extrabold text-slate-900 tracking-tight font-mono">
              {totalSignsCount}
            </span>
          </div>
        </div>

        {/* Transcript Card */}
        <div className="rounded-2xl border border-slate-200/80 p-5 bg-white flex flex-col gap-3">
          <h2 className="text-xs font-bold uppercase tracking-wider text-slate-500">
            Your session transcript
          </h2>

          {totalSignsCount > 0 ? (
            <div className="min-h-[72px] flex items-center">
              <p className="text-base sm:text-lg font-bold text-slate-900 tracking-wide leading-relaxed break-words font-mono">
                {transcriptText}
              </p>
            </div>
          ) : (
            <div className="min-h-[72px] flex flex-col justify-center text-slate-400 text-xs sm:text-sm italic">
              <p>No signs were confirmed during this session.</p>
              <p className="text-slate-400 text-xs mt-0.5">Start another session when you're ready.</p>
            </div>
          )}

          {/* Transcript Actions */}
          <div className="flex items-center gap-2 pt-2 border-t border-slate-100">
            <button
              onClick={handleCopy}
              disabled={totalSignsCount === 0}
              className={`min-h-[40px] inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-semibold transition-all border ${
                totalSignsCount === 0
                  ? 'bg-slate-50 text-slate-300 border-slate-200/50 cursor-not-allowed'
                  : copied
                  ? 'bg-teal-50 text-[#068D9D] border-teal-200'
                  : 'bg-white text-slate-700 hover:bg-slate-50 hover:text-slate-900 border-slate-200 shadow-2xs'
              }`}
              title="Copy confirmed signs to clipboard"
              aria-label="Copy transcript"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-[#068D9D]" aria-hidden="true" />
                  <span>Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5 text-slate-500" aria-hidden="true" />
                  <span>Copy transcript</span>
                </>
              )}
            </button>

            <button
              onClick={handleDownload}
              disabled={totalSignsCount === 0}
              className={`min-h-[40px] inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl text-xs font-semibold transition-all border ${
                totalSignsCount === 0
                  ? 'bg-slate-50 text-slate-300 border-slate-200/50 cursor-not-allowed'
                  : 'bg-white text-slate-700 hover:bg-slate-50 hover:text-slate-900 border-slate-200 shadow-2xs'
              }`}
              title="Download session summary as text file"
              aria-label="Download transcript"
            >
              <Download className="w-3.5 h-3.5 text-slate-500" aria-hidden="true" />
              <span>Download</span>
            </button>
          </div>
        </div>

        {/* Primary Start New Session Action */}
        <button
          onClick={onStartNewSession}
          className="min-h-[48px] w-full py-3.5 px-5 rounded-2xl font-bold text-sm bg-[#068D9D] hover:bg-[#05707d] text-white shadow-sm hover:shadow transition-all flex items-center justify-center gap-2 active:scale-[0.99] focus-visible:ring-2 focus-visible:ring-[#068D9D]"
          aria-label="Start new translation session"
        >
          <RotateCcw className="w-4 h-4 shrink-0" aria-hidden="true" />
          <span>Start new session</span>
        </button>

        <p className="text-[11px] text-center text-slate-400">
          SignFlow saves session summaries locally in your browser memory for privacy.
        </p>
      </div>
    </div>
  );
}
